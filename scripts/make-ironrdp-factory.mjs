// Turn the standalone RDP bundle into a factory. Each call owns all of wasm-bindgen's glue (classes, heap tables,
// finalizers and cached memory views), while the caller shares a compiled WebAssembly.Module. No runtime eval,
// extra ESM URLs or imports per desktop. The public bundle and WASM stay unchanged.
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
const ts = createRequire(import.meta.url)(process.env.TRD_TYPESCRIPT_PATH || 'typescript')

export function makeFactory (source) {
    const ast = ts.createSourceFile('ironrdp.js', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
    if (ast.parseDiagnostics.length || source.includes('__trd')) throw new Error('unexpected RDP bundle syntax')
    const exports = []
    const edits = []
    let wasm
    for (const statement of ast.statements) {
        if (ts.isExportDeclaration(statement)) {
            if (statement.moduleSpecifier || !statement.exportClause || !ts.isNamedExports(statement.exportClause)) {
                throw new Error('the RDP bundle must have only local named exports')
            }
            for (const entry of statement.exportClause.elements) {
                const local = entry.propertyName ?? entry.name
                if (!ts.isIdentifier(local) || !ts.isIdentifier(entry.name)) throw new Error('unexpected RDP export')
                exports.push([entry.name.text, local.text])
            }
            edits.push([statement.getStart(ast), statement.end, ''])
        } else if (ts.isImportDeclaration(statement) || ts.isExportAssignment(statement) ||
            statement.modifiers?.some(m => m.kind === ts.SyntaxKind.ExportKeyword)) {
            throw new Error('the RDP bundle must be standalone')
        }
    }
    const visit = node => {
        // wasm-bindgen's finalizer assigns instance.exports to its module-scoped WASM binding. Watch those calls so
        // asynchronous traps in event callbacks can end the owning desktop even if its run() promise never settles.
        if (ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.EqualsToken &&
            ts.isIdentifier(node.left) && ts.isPropertyAccessExpression(node.right) && node.right.name.text === 'exports') {
            if (wasm) throw new Error('more than one WASM exports binding')
            wasm = node.left.text
            edits.push([node.right.getStart(ast), node.right.end, `__trdWatchExports(${node.right.getText(ast)})`])
        }
        ts.forEachChild(node, visit)
    }
    visit(ast)
    const init = exports.find(([name]) => name === 'init')?.[1]
    if (!wasm || !init || !exports.some(([name]) => name === 'Backend') || exports.some(([name]) => name === 'runtime')) {
        throw new Error('the RDP bundle has no recognized WASM initializer/backend')
    }
    let body = source
    for (const [start, end, replacement] of edits.sort((a, b) => b[0] - a[0])) body = body.slice(0, start) + replacement + body.slice(end)
    return `// Generated by scripts/make-ironrdp-factory.mjs from iron-remote-desktop-rdp.js.\n` +
`export async function createBackend (__trdModule, __trdLevel = 'INFO') {
    if (!(__trdModule instanceof WebAssembly.Module)) throw new TypeError('createBackend needs a compiled WebAssembly.Module');
    let __trdTrap;
    const __trdListeners = new Set();
    function __trdWatchExports (raw) {
        return Object.fromEntries(Object.entries(raw).map(([name, value]) => [name, typeof value !== 'function' ? value : (...args) => {
            // Rust destructors cannot safely run after an abort. Late JS finalizers become harmless.
            if (__trdTrap) {
                if (/^__wbg_.*_free$|^__wbindgen_destroy_closure$/.test(name)) return;
                throw __trdTrap;
            }
            try { return value(...args); } catch (error) {
                if (error instanceof WebAssembly.RuntimeError) {
                    __trdTrap = error;
                    for (const listener of __trdListeners) listener(error);
                    __trdListeners.clear();
                }
                throw error;
            }
        }]));
    }
${body.trimEnd()}
    await ${init}(__trdLevel, __trdModule);
    return {
${exports.map(([name, local]) => `        ${name}: ${local},`).join('\n')}
        runtime: {
            get memory () { return ${wasm}.memory; },
            get trapped () { return __trdTrap; },
            onTrap (listener) {
                if (__trdTrap) listener(__trdTrap);
                else __trdListeners.add(listener);
                return () => __trdListeners.delete(listener);
            },
        },
    };
}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const input = process.argv[2] ?? fileURLToPath(new URL('../vendor/iron-remote-desktop-rdp.js', import.meta.url))
    const output = process.argv[3] ?? fileURLToPath(new URL('../vendor/ironrdp-factory.js', import.meta.url))
    writeFileSync(output, makeFactory(readFileSync(input, 'utf8')))
}
